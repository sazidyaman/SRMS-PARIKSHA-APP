// Timetable Collision Detection Engine (Room, Faculty, Batch)
// ----------------------------------------------------
export function detectTimetableCollisions(slotList: TimetableSlot[]): TimetableCollision[] {
  const collisions: TimetableCollision[] = [];
  const processedPairs = new Set<string>();

  for (let i = 0; i < slotList.length; i++) {
    for (let j = i + 1; j < slotList.length; j++) {
      const a = slotList[i];
      const b = slotList[j];

      if (a.day !== b.day) continue;

      const overlap = Math.max(a.startMinutes, b.startMinutes) < Math.min(a.endMinutes, b.endMinutes);
      if (!overlap) continue;

      const pairKey = [a.id, b.id].sort().join(':::');
      if (processedPairs.has(pairKey)) continue;

      // 1. Room Clash Check (Same room double-booked at the same time across different classes)
      if (
        a.room &&
        b.room &&
        a.room.trim().toUpperCase() === b.room.trim().toUpperCase() &&
        a.branch !== b.branch &&
        !a.room.toUpperCase().includes('CENTRAL-LIB') &&
        !a.room.toUpperCase().includes('CAMPUS') &&
        !a.room.toUpperCase().includes('HALL')
      ) {
        processedPairs.add(pairKey);
        collisions.push({
          id: `clash-room-${pairKey}`,
          type: 'room_clash',
          day: a.day,
          timeSlot: `${a.timeSlot}`,
          slotAId: a.id,
          slotBId: b.id,
          slotA: a,
          slotB: b,
          description: `ROOM DOUBLE-BOOKED: Room ${a.room} is scheduled simultaneously for ${a.branch} (${a.subjectCode}) and ${b.branch} (${b.subjectCode}) on ${a.day} at ${a.timeSlot}.`,
          recommendation: `Reallocate ${b.branch} to an unoccupied room (e.g., Room 318 or Lab 2C) or reschedule the period.`,
        });
        continue;
      }

      // 2. Faculty Clash Check (Same teacher assigned to two places at once)
      if (
        a.facultyCode &&
        b.facultyCode &&
        a.facultyCode.trim().toUpperCase() === b.facultyCode.trim().toUpperCase() &&
        !['LIB', 'N/A', 'SELF', 'CLUB'].includes(a.facultyCode.toUpperCase()) &&
        (a.room !== b.room || a.branch !== b.branch)
      ) {
        processedPairs.add(pairKey);
        collisions.push({
          id: `clash-faculty-${pairKey}`,
          type: 'faculty_clash',
          day: a.day,
          timeSlot: `${a.timeSlot}`,
          slotAId: a.id,
          slotBId: b.id,
          slotA: a,
          slotB: b,
          description: `FACULTY DOUBLE-BOOKED: ${a.facultyName} (${a.facultyCode}) is assigned to teach both ${a.branch} in Room ${a.room} and ${b.branch} in Room ${b.room} on ${a.day} at ${a.timeSlot}.`,
          recommendation: `Assign a substitute faculty for ${b.branch} or swap the lecture period.`,
        });
        continue;
      }

      // 3. Branch Clash Check (Same branch or batch assigned conflicting simultaneous lectures)
      const isBatchConflict = !a.batchGroup || !b.batchGroup || a.batchGroup === b.batchGroup;
      if (a.branch === b.branch && isBatchConflict) {
        processedPairs.add(pairKey);
        collisions.push({
          id: `clash-branch-${pairKey}`,
          type: 'branch_clash',
          day: a.day,
          timeSlot: `${a.timeSlot}`,
          slotAId: a.id,
          slotBId: b.id,
          slotA: a,
          slotB: b,
          description: `STUDENT BATCH OVERLAP: Branch ${a.branch} has two conflicting subjects scheduled at the same time: ${a.subjectCode} (Room ${a.room}) and ${b.subjectCode} (Room ${b.room}).`,
          recommendation: `Remove one conflicting slot or adjust its time period.`,
        });
      }
    }
  }

  return collisions;
}

